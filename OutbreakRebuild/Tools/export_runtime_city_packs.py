"""Bundle authoritative pack recipes/blueprints for the native runtime; --check needs only Python stdlib."""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'Assets/Outbreak/Core/CityPackData.cs'
MANIFEST = ROOT / 'CityReferences/runtime/manifest.json'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def export():
    # Geometry validation is delegated to the original pack code, never re-created in this exporter.
    import generate_district_city as districts
    import generate_reference_city as buildings
    catalogue = json.loads(districts.CATALOGUE.read_text())
    inputs = [districts.CATALOGUE, ROOT/'Tools/generate_district_city.py', ROOT/'Tools/generate_reference_city.py', ROOT/'Tools/generate_seeded_city.py', Path(__file__).resolve()]
    profiles = []
    for kind, spec in catalogue['districts'].items():
        recipe = districts.district_recipe(kind)
        settings = recipe['street_settings']
        if spec['reference_id']:
            inputs.append(ROOT/'CityReferences/atlas'/(spec['reference_id']+'.profile.json'))
        average = sum(w*h for w,h in recipe['footprint_sizes'])/len(recipe['footprint_sizes'])
        profiles.append((kind, spec['name'], int(settings['block_width_cells']), int(settings['block_height_cells']), math.ceil(settings['setback_cells']), recipe['lot_gap_cells'], round(settings['block_variation']*1000), round(settings['loop_chance']*1000), round(settings['dead_end_chance']*1000), round(settings['park_fraction']*1000), math.ceil(settings['road_width_cells']), math.ceil(settings['sidewalk_width_cells']), max(20,min(80,round(average)))))
    sources = {str(p.relative_to(ROOT)):sha(p) for p in sorted(set(inputs))}
    source_hash = hashlib.sha256(json.dumps(sources,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    lines = ['// Generated by Tools/export_runtime_city_packs.py. Do not edit; source hashes are in CityReferences/runtime/manifest.json.', '// Reference calibration: © OpenStreetMap contributors, ODbL1.0; see CityReferences/NOTICE.md. Layouts are fictional project templates.', 'namespace Outbreak.Core {', 'internal sealed class PackProfile { internal string Id,Name; internal int Width,Height,Setback,Gap,Variation,Loops,Spurs,Parks,Road,Sidewalk,Spacious; internal PackProfile(string id,string name,int w,int h,int setback,int gap,int variation,int loops,int spurs,int parks,int road,int sidewalk,int spacious){Id=id;Name=name;Width=w;Height=h;Setback=setback;Gap=gap;Variation=variation;Loops=loops;Spurs=spurs;Parks=parks;Road=road;Sidewalk=sidewalk;Spacious=spacious;} }', 'internal sealed class PackFixture { internal string Role; internal int[] Cells; internal PackFixture(string role,int[] cells){Role=role;Cells=cells;} }', 'internal sealed class PackBlueprint { internal BuildingUse Use; internal string Id; internal int Width,Height; internal int[] Walls,Doors,External,Anchors,Phone; internal string[] RoomIds,Roles; internal PackFixture[] Fixtures; internal PackBlueprint(BuildingUse use,string id,int w,int h,int[] walls,int[] doors,int[] external,int[] anchors,string[] roomIds,string[] roles,int[] phone,PackFixture[] fixtures){Use=use;Id=id;Width=w;Height=h;Walls=walls;Doors=doors;External=external;Anchors=anchors;RoomIds=roomIds;Roles=roles;Phone=phone;Fixtures=fixtures;} }', 'internal static class CityPackData {', 'internal const string SourceHash="'+source_hash+'", Version="city-pack-runtime-2", LayoutVersion="'+buildings.BUILDING_LAYOUT_VERSION+'";', 'internal static readonly PackProfile[] Profiles=new PackProfile[]{']
    cs = lambda v:json.dumps(v,ensure_ascii=False) if isinstance(v,str) else str(v)
    for profile in profiles:
        lines.append('new PackProfile('+','.join(map(cs,profile))+'),')
    lines += ['};','internal static readonly PackBlueprint[] Blueprints=new PackBlueprint[]{']
    ints = lambda pairs:'new int[]{'+','.join(str(n) for p in pairs for n in p)+'}'
    strings = lambda values:'new string[]{'+','.join(map(cs,values))+'}'
    for kind,use in [('house','Home'),('store','Store'),('distribution-center','DistributionCenter')]:
        for variant in buildings.BUILDING_VARIANTS:
            for rotation in range(4):
                b=buildings.building_blueprint(kind,variant,rotation)
                phone=[2,2];w,h=buildings.building_blueprint(kind,variant)['width'],buildings.building_blueprint(kind,variant)['height']
                for _ in range(rotation):phone,w,h=[h-1-phone[1],phone[0]],h,w
                fixtures='new PackFixture[]{'+','.join('new PackFixture('+cs(f['role'])+','+ints(f['cells'])+')' for f in b['fixtures'])+'}'
                lines.append('new PackBlueprint(BuildingUse.'+use+','+','.join([cs(b['id']),str(b['width']),str(b['height']),ints(b['walls']),ints([d['cell'] for d in b['doors']]),ints([d['cell'] for d in b['doors'] if d['external']]),ints([room['cells'][0] for room in b['rooms']]),strings([room['id'] for room in b['rooms']]),strings([room['role'] for room in b['rooms']]),ints([phone]),fixtures])+'),')
    lines += ['};','} }','']
    OUTPUT.write_text('\n'.join(lines))
    MANIFEST.parent.mkdir(parents=True,exist_ok=True)
    MANIFEST.write_text(json.dumps({'runtime_version':'city-pack-runtime-2','source_sha256':source_hash,'sources':sources,'output':str(OUTPUT.relative_to(ROOT)),'output_sha256':sha(OUTPUT),'districts':[p[0] for p in profiles],'blueprints':24,'attribution':'See CityReferences/NOTICE.md; © OpenStreetMap contributors, ODbL1.0. Runtime geometry is an explicit fictional adaptation, not Python recipe replay.'},indent=2)+'\n')


def check():
    manifest=json.loads(MANIFEST.read_text())
    for path,want in manifest['sources'].items():
        if sha(ROOT/path)!=want:raise ValueError('Runtime city pack source changed: '+path+'; export again with atlas Python.')
    if sha(ROOT/manifest['output'])!=manifest['output_sha256']:raise ValueError('Generated runtime city data changed; export again.')
    print('PASS runtime city-pack sources and bundled data: 9 district themes, 24 validated blueprint variants/rotations.')


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if not args.check:export()
    check()
